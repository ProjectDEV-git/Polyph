#!/usr/bin/env node
// Bundles locales/<lang>/*.ftl into packages/ui/src/i18n/locales.gen.ts so every
// bundler (Vite, Next.js, Vitest) gets the same strings without loaders.
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dir = join(root, "locales");
const out = {};
for (const lang of readdirSync(dir).sort()) {
  const p = join(dir, lang);
  if (!statSync(p).isDirectory()) continue;
  out[lang] = readdirSync(p)
    .filter((f) => f.endsWith(".ftl"))
    .sort()
    .map((f) => readFileSync(join(p, f), "utf8"))
    .join("\n");
}
const target = join(root, "packages/ui/src/i18n");
mkdirSync(target, { recursive: true });
const body = `// Generated by scripts/bundle-locales.mjs from locales/. Do not edit.\nexport const LOCALES: Record<string, string> = ${JSON.stringify(out)};\n`;
const file = join(target, "locales.gen.ts");
let old = "";
try {
  old = readFileSync(file, "utf8");
} catch {}
if (old !== body) writeFileSync(file, body);
